package io.jancher.launcher.model

/**
 * Видимость — одно состояние, а не набор независимых флагов.
 *
 * «Архивировано и одновременно скрыто» не имеет осмысленного поведения:
 * непонятно, показывать ли приложение в разделе «Архив». Взаимное
 * исключение убирает целый класс невозможных состояний.
 */
enum class Visibility {
    /** Обычное приложение: видно в группах и в поиске. */
    VISIBLE,

    /** Убрано из групп, но есть в разделе «Архив» и, по настройке, в поиске. */
    ARCHIVED,

    /**
     * Не видно нигде, кроме настроек Jancher. Это НЕ приватность:
     * приложение остаётся в системных настройках и в списке недавних.
     */
    HIDDEN,
}
